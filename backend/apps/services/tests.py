def test_service_clean_rejects_price_to_less_than_price_from():
    cat = ServiceCategory.objects.create(name="Анализы", slug="analizy")
    svc = Service(
        category=cat,
        name="Анализ крови",
        slug="analiz-krovi",
        price_from=Decimal("500.00"),
        price_to=Decimal("100.00"),
    )
    with pytest.raises(ValidationError) as exc:
        svc.clean()

    assert "price_to" in exc.value.message_dict


