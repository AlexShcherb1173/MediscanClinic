def test_popular_services_context_returns_featured_sorted_and_limited():
    cat = ServiceCategory.objects.create(name="УЗИ", slug="uzi", is_active=True)

    # Create 5 featured -> should return only first 4 by featured_order then name
    Service.objects.create(
        category=cat, name="B", slug="b", price_from=Decimal("100.00"),
        is_active=True, is_featured=True, featured_order=2,
    )
    Service.objects.create(
        category=cat, name="A", slug="a", price_from=Decimal("100.00"),
        is_active=True, is_featured=True, featured_order=2,
    )
    Service.objects.create(
        category=cat, name="C", slug="c", price_from=Decimal("100.00"),
        is_active=True, is_featured=True, featured_order=1,
    )
    Service.objects.create(
        category=cat, name="D", slug="d", price_from=Decimal("100.00"),
        is_active=True, is_featured=True, featured_order=3,
    )
    Service.objects.create(
        category=cat, name="E", slug="e", price_from=Decimal("100.00"),
        is_active=True, is_featured=True, featured_order=4,
    )

    rf = RequestFactory()
    request = rf.get("/")
    ctx = popular_services(request)

    qs = list(ctx["popular_services"])
    assert len(qs) == 4
    # first should be featured_order=1 -> C
    assert qs[0].slug == "c"


