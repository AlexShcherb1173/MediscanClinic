def _create_services_dataset():
    active_cat = ServiceCategory.objects.create(name="УЗИ", slug="uzi", is_active=True)
    inactive_cat = ServiceCategory.objects.create(name="Скрытая", slug="hidden", is_active=False)

    # Active services in active category
    s1 = Service.objects.create(
        category=active_cat, name="УЗИ сердца", slug="uzi-serdca",
        price_from=Decimal("100.00"), is_active=True, is_featured=True, featured_order=1,
    )
    s2 = Service.objects.create(
        category=active_cat, name="УЗИ сосудов", slug="uzi-sosudov",
        price_from=Decimal("200.00"), is_active=True, is_featured=False,
    )
    s3 = Service.objects.create(
        category=active_cat, name="УЗИ печени", slug="uzi-pecheni",
        price_from=Decimal("300.00"), is_active=True, is_featured=False,
    )

    # Inactive service (should not appear)
    Service.objects.create(
        category=active_cat, name="Неактивная", slug="inactive",
        price_from=Decimal("150.00"), is_active=False,
    )

    # Service in inactive category (should not appear)
    Service.objects.create(
        category=inactive_cat, name="Категория скрыта", slug="hidden-cat",
        price_from=Decimal("150.00"), is_active=True,
    )

    return active_cat, s1, s2, s3


def test_service_list_view_basic(client):
    _create_services_dataset()

    url = reverse("services:list")
    resp = client.get(url)

    assert resp.status_code == 200
    services = list(resp.context["services"])
    assert all(s.is_active for s in services)
    # inactive service and service in inactive category excluded
    slugs = {s.slug for s in services}
    assert "inactive" not in slugs
    assert "hidden-cat" not in slugs


def test_service_list_view_saves_return_url_in_session(client):
    _create_services_dataset()

    url = reverse("services:list") + "?q=узи&sort=-price"
    resp = client.get(url)
    assert resp.status_code == 200
    assert client.session.get("services_return_url") == "/services/?q=%D1%83%D0%B7%D0%B8&sort=-price"


def test_service_list_view_filter_by_category(client):
    cat, *_ = _create_services_dataset()

    url = reverse("services:category", kwargs={"category_slug": cat.slug})
    resp = client.get(url)

    assert resp.status_code == 200
    services = list(resp.context["services"])
    assert all(s.category_id == cat.id for s in services)


